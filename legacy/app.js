function tokenise(text) {
  return text
    .toLowerCase()
    .replace(/\n/g, ' ')
    .match(/[a-z0-9']+|[.,;:!?'"()\-–—]/g) || [];
}

function escHtml(s) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function lcsAlign(ref, stu) {
  const m = ref.length, n = stu.length;
  const dp = Array.from({ length: m + 1 }, () => new Uint16Array(n + 1));
  for (let i = 1; i <= m; i++) {
    for (let j = 1; j <= n; j++) {
      if (ref[i - 1] === stu[j - 1]) {
        dp[i][j] = dp[i - 1][j - 1] + 1;
      } else {
        dp[i][j] = Math.max(dp[i - 1][j], dp[i][j - 1]);
      }
    }
  }
  const ops = [];
  let i = m, j = n;
  while (i > 0 || j > 0) {
    if (i > 0 && j > 0 && ref[i - 1] === stu[j - 1]) {
      ops.push({ type: 'ok', ref: ref[i - 1], stu: stu[j - 1] });
      i--; j--;
    } else if (j > 0 && (i === 0 || dp[i][j - 1] >= dp[i - 1][j])) {
      ops.push({ type: 'insert', stu: stu[j - 1] });
      j--;
    } else {
      if (j > 0 && dp[i][j] === dp[i - 1][j] && dp[i][j] === dp[i][j - 1]) {
        ops.push({ type: 'replace', ref: ref[i - 1], stu: stu[j - 1] });
        i--; j--;
      } else {
        ops.push({ type: 'delete', ref: ref[i - 1] });
        i--;
      }
    }
  }
  ops.reverse();
  return ops;
}

function checkDictation() {
  const name = document.getElementById('student-name').value.trim();
  const num = document.getElementById('dictation-num').value;
  const studentRaw = document.getElementById('student-text').value.trim();

  if (!name) { alert('Please enter the student name.'); return; }
  if (!num) { alert('Please select a dictation number.'); return; }
  if (!studentRaw) { alert('Please type the dictation text.'); return; }
  if (!DICTATIONS[num]) { alert('Dictation not found.'); return; }

  const refTokens = tokenise(DICTATIONS[num]);
  const stuTokens = tokenise(studentRaw);
  const diff = lcsAlign(refTokens, stuTokens);

  let errors = 0;
  const total = refTokens.length;
  let html = '';

  diff.forEach(op => {
    if (op.type === 'ok') {
      html += `<span class="w-ok">${escHtml(op.ref)}</span> `;
    } else if (op.type === 'replace') {
      html += `<span class="w-err" title="Expected: ${escHtml(op.ref)}">${escHtml(op.stu)}</span> `;
      errors++;
    } else if (op.type === 'delete') {
      html += `<span class="w-missing">[${escHtml(op.ref)}]</span> `;
      errors++;
    } else if (op.type === 'insert') {
      html += `<span class="w-extra">${escHtml(op.stu)}</span> `;
    }
  });

  document.getElementById('res-name').textContent = name;
  document.getElementById('res-num').textContent = 'Dictation ' + num;
  document.getElementById('wrong-words').textContent = errors;
  document.getElementById('diff-output').innerHTML = html;

  const pct = total > 0 ? ((total - errors) / total) * 100 : 0;
  const badge = document.getElementById('grade-badge');
  if (pct >= 85) {
    badge.className = 'grade-label grade-a';
    badge.textContent = `Excellent — ${pct.toFixed(0)}% correct`;
  } else if (pct >= 65) {
    badge.className = 'grade-label grade-b';
    badge.textContent = `Good effort — ${pct.toFixed(0)}% correct`;
  } else {
    badge.className = 'grade-label grade-c';
    badge.textContent = `Needs practice — ${pct.toFixed(0)}% correct`;
  }

  const resultsEl = document.getElementById('results');
  resultsEl.classList.add('visible');
  resultsEl.scrollIntoView({ behavior: 'smooth', block: 'start' });
}

function resetAll() {
  document.getElementById('student-name').value = '';
  document.getElementById('dictation-num').value = '';
  document.getElementById('student-text').value = '';
  document.getElementById('results').classList.remove('visible');
  window.scrollTo({ top: 0, behavior: 'smooth' });
}
